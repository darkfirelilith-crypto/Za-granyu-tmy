export function VtmHelpDialog({ tabId, open, onClose }: { tabId: string; open: boolean; onClose: () => void }) {
  return <HelpDialogBody content={VTM_HELP[tabId]} open={open} onClose={onClose} moon={false} />;
}

export function W5HelpDialog({ tabId, open, onClose }: { tabId: string; open: boolean; onClose: () => void }) {
  return <HelpDialogBody content={W5_HELP[tabId]} open={open} onClose={onClose} moon />;
}

function HelpDialogBody({
  content,
  open,
  onClose,
  moon,
}: {
  content?: HelpTabContent;
  open: boolean;
  onClose: () => void;
  moon?: boolean;
}) {
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") onClose(); };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  if (!open || !content) return null;

  return (
    <div
      className="fixed inset-0 z-50 flex items-start justify-center p-3 md:p-6 overflow-y-auto vtm-scroll"
      style={{ background: "rgba(0,0,0,0.85)" }}
      role="dialog"
      aria-modal="true"
      aria-label={`Справка: ${content.title}`}
    >
      <div className={`vtm-help-dlg w-full max-w-3xl my-4 ${moon ? "vtm-help-dlg--moon" : ""}`}>
        <div className="vtm-help-head">
          <span className={`vtm-stamp ${moon ? "vtm-w5-stamp" : ""}`}>{moon ? "🐺 Справка стаи" : "Справка"}</span>
          <h2 className="vtm-display text-lg text-[#d9c7b6] mt-2">{content.title}</h2>
          <p className="vtm-hint mt-1 !text-[0.84rem]">{content.intro}</p>
          <button onClick={onClose} className="vtm-pstudio-close" aria-label="Закрыть справку">✕</button>
        </div>
        <div className="p-4 space-y-3 max-h-[65vh] overflow-y-auto vtm-scroll">
          {content.entries.map((e) => (
            <section key={e.q} className="vtm-frame rounded-md p-3 space-y-1.5" style={{ background: moon ? "rgba(142,166,201,0.05)" : "rgba(138,26,29,0.05)" }}>
              <h3 className="vtm-label text-[0.76rem] text-[#d6a840]">{e.q}</h3>
              {e.a.map((p, i) => (
                <p key={i} className="text-[0.92rem] leading-relaxed text-[#c4ac9d]">{p}</p>
              ))}
            </section>
          ))}
          <p className="vtm-hint text-center !text-[0.77rem] pt-1 pb-2">
            Полный справочник — во вкладке «База знаний». Спорные места решает Рассказчик.
          </p>
        </div>
      </div>
    </div>
  );
}
