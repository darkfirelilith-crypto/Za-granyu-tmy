// ---------- Генерация имени ----------

export function generateName(clanId?: string): VampireName {
  const clans = Object.keys(NAME_SETS);
  const clan = clanId && NAME_SETS[clanId] ? clanId : pick(clans);
  const set = NAME_SETS[clan];
  const first = pick(set.first);
  const last = pick(set.last);
  const epithet = pick(EPITHETS);
  const origin = pick(set.origins);
  const clanName = CLAN_LABELS[clan] || clan;
  // 50% шанс добавить эпитет к имени
  const useEpithet = Math.random() < 0.5;
  const full = useEpithet
    ? `${first} «${epithet}» ${last}`
    : `${first} ${last}`;

  return {
    id: `name-${Date.now()}-${Math.floor(Math.random() * 10000)}`,
    first,
    last,
    epithet,
    clan,
    clanName,
    origin,
    full,
  };
}

export function generateNameBatch(count: number, clanId?: string): VampireName[] {
  const names: VampireName[] = [];
  for (let i = 0; i < count; i++) {
    names.push(generateName(clanId));
  }
  return names;
}

