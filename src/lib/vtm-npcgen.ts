// ---------- Генерация NPC ----------

export function generateNpc(clanId?: string): NpcCard {
  const clans = ["brujah", "ventru", "gangrel", "malkavian", "nosferatu", "toreador", "tremere", "banu_haqim", "lasombra", "hecata", "ministry", "ravnos", "salubri", "tzimisce", "caitiff", "thinblood"];
  const clan = clanId || pick(clans);
  const age = pick(NPC_AGES);
  const sect = pick(SECT_OPTIONS);
  // Слабокровные всегда Автаркия/Анархи
  const actualSect = clan === "thinblood" ? pick([SECT_OPTIONS[1], SECT_OPTIONS[3]]) : sect;
  const predatorIds = ["beast", "gentleman", "idol", "siren", "morpheus", "raider", "clansman", "graverobber", "scenequeen", "farmer", "alchemist", "blood_leech", "sandman", "cleaver", "consensualist", "extortionist", "roadside", "grim_reaper", "osiris", "trapdoor", "faceless"];
  const predator = pick(predatorIds);

  const discIds = CLAN_DISCIPLINES[clan] || CLAN_DISCIPLINES.caitiff;
  const disciplines = discIds
    .filter((d) => d && DISCIPLINE_NAMES[d])
    .map((d, i) => ({
      name: DISCIPLINE_NAMES[d],
      level: Math.max(1, Math.min(5, age.bp + (i === 0 ? 1 : 0) + Math.floor(Math.random() * 2))),
    }))
    .slice(0, 3);

  const name = pickName(clan);
  const role = pick(NPC_ROLES);
  const demeanor = pick(NPC_DEMEANORS);
  const hook = pick(NPC_HOOKS);
  const attitude = pick(NPC_ATTITUDES);
  const quote = pick(NPC_QUOTES);

  // Имя клана (упрощённо — без импорта из vtm-data, чтобы избежать циклов)
  const clanNames: Record<string, string> = {
    brujah: "Бруха", ventru: "Вентру", gangrel: "Гангрел", malkavian: "Малкавиане",
    nosferatu: "Носферату", toreador: "Тореадор", tremere: "Тремер",
    banu_haqim: "Бану Хаким", lasombra: "Ласомбра", hecata: "Геката",
    ministry: "Министерство", ravnos: "Равнос", salubri: "Салюбри",
    tzimisce: "Тзимице", caitiff: "Каитиф", thinblood: "Слабокровный",
  };
  const predatorNames: Record<string, string> = {
    beast: "Бестия", gentleman: "Джентльмен", idol: "Идол", siren: "Искуситель",
    morpheus: "Морфей", raider: "Налётчик", clansman: "Семьянин", graverobber: "Суррогатчик",
    scenequeen: "Тусовщик", farmer: "Фермер", alchemist: "Алхимик", blood_leech: "Кровавый пияв",
    sandman: "Песочный человек", cleaver: "Кровник", consensualist: "Доброволец",
    extortionist: "Шантажист", roadside: "Бездорожный", grim_reaper: "Жнец",
    osiris: "Осирис", trapdoor: "Лючок", faceless: "Безликий",
  };

  return {
    id: `npc-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    name,
    clan,
    clanName: clanNames[clan] || clan,
    generation: age.gen,
    bloodPotency: age.bp,
    sect: actualSect.id,
    sectName: actualSect.name,
    predator,
    predatorName: predatorNames[predator] || predator,
    disciplines,
    role: role.name,
    age: age.name,
    demeanor,
    hook,
    attitude,
    quote,
  };
}

export function generateNpcBatch(count: number, clanId?: string): NpcCard[] {
  const npcs: NpcCard[] = [];
  for (let i = 0; i < count; i++) {
    npcs.push(generateNpc(clanId));
  }
  return npcs;
}

