// ---------- Случайный выбор ----------

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function pickName(clanId: string): string {
  const nameSet = NPC_NAMES[clanId] || NPC_NAMES.caitiff;
  return `${pick(nameSet.first)} ${pick(nameSet.last)}`;
}

