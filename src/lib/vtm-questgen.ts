// ---------- Случайный выбор ----------

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function difficultyHint(): { difficulty: number; label: string } {
  const d = Math.floor(Math.random() * 5) + 1;
  const labels = [
    "1 — Лёгкое: 1-2 проверки, минимальный риск.",
    "2 — Простое: 2-3 проверки, риск мелкий.",
    "3 — Среднее: 3-4 проверки, риск серьёзный.",
    "4 — Сложное: 4-5 проверок, риск высокий.",
    "5 — Смертельное: 5+ проверок, риск Конечной Смерти.",
  ];
  return { difficulty: d, label: labels[d - 1] };
}

// ---------- Генерация квеста ----------

export function generateQuest(): QuestCard {
  const title = pick(QUEST_TITLES);
  const client = pick(QUEST_CLIENTS);
  const target = pick(QUEST_TARGETS);
  const type = pick(QUEST_TYPES);
  const { difficulty, label } = difficultyHint();
  const reward = pick(QUEST_REWARDS);
  const risk = pick(QUEST_RISKS);
  const deadline = pick(QUEST_DEADLINES);
  const includeTwist = Math.random() < 0.4;
  const twist = includeTwist ? pick(QUEST_TWISTS) : undefined;

  return {
    id: `quest-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    title,
    client: client.name,
    clientDesc: client.desc,
    target: target.name,
    targetDesc: target.desc,
    type,
    difficulty,
    reward,
    risk,
    deadline,
    twist,
  };
}

export function generateQuestBatch(count: number): QuestCard[] {
  const quests: QuestCard[] = [];
  for (let i = 0; i < count; i++) {
    quests.push(generateQuest());
  }
  return quests;
}

