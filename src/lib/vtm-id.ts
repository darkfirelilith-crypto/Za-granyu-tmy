// ============================================================
// Единый генератор уникальных идентификаторов «Маскарада».
// Раунд 23: раньше хроника бросков и карточки Даров/Обрядов/Снаряжения
// рождали id как `prefix-Date.now().toString(36)` — два клика в одну
// миллисекунду давали ДУБЛИ КЛЮЧЕЙ (React «two children with the same key»).
// Монотонный счётчик + случайный хвост делают столкновение невозможным.
// ============================================================

let seq = 0;

/** Уникальный id вида `prefix-<время36>-<счётчик36>-<случайное36>`. */
export function vtmUid(prefix: string): string {
  seq += 1;
  return `${prefix}-${Date.now().toString(36)}-${seq.toString(36)}-${Math.random().toString(36).slice(2, 6)}`;
}
