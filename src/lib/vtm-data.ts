// ---------- Типы ----------

export interface VtmInfo {
  name: string;        // имя вампира
  concept: string;     // концепция (кем был / кем стал)
  chronicle: string;   // хроника
  sire: string;        // сир (создатель)
  occupation: string;  // род деятельности (смертная профессия / род занятий)
  generation: number;  // поколение 5..16 (0 = не выбрано)
  sect: string;        // id секты из SECTS
  clan: string;        // id клана из CLANS (включая caitif / thinblood)
  predator: string;    // id стиля охоты из PREDATOR_TYPES
  ambition: string;    // Цель (большая, на всю хронику)
  desire: string;      // Желание (ближняя цель, текущая арка)
  principle1: string;  // Принцип 1 («никогда…» / «всегда…»)
  principle2: string;  // Принцип 2
  principle3: string;  // Принцип 3
  anchor1: string;     // Опора 1 (кто держит Человечность)
  anchor2: string;     // Опора 2
  anchor3: string;     // Опора 3
  description: string; // внешность
  history: string;     // предыстория
  portrait: string;      // dataURL (до 480px)
  portraitThumb: string; // dataURL (96px) для карточек архива
}

export interface VtmAttributes {
  str: number; // Сила
  dex: number; // Ловкость
  sta: number; // Выносливость
  cha: number; // Обаяние
  man: number; // Манипуляция
  com: number; // Самообладание
  int: number; // Интеллект
  wit: number; // Смекалка
  res: number; // Упорство
}

export interface VtmSkillState {
  key: string | null; // id из SKILL_LIBRARY или null для кастомного
  name: string;
  value: number; // 0–5
  spec: string;  // специализация («выслеживание», «палинг…»)
  xp: number;    // вложено опыта (для истории прокачки)
}

export interface VtmDisciplineState {
  key: string | null;  // id из DISCIPLINES или null для редкой/своей
  name: string;
  value: number;       // 0–5
  powers: Record<number, string>; // уровень → выбранная сила (название)
  xp: number;
  description?: string;          // описание своей Дисциплины (полная кастомизация)
  powerNotes?: Record<number, string>; // уровень → описание своей силы
}

export interface VtmAdvantageEntry {
  id: string;
  name: string;
  kind: "background" | "merit" | "flaw" | "thinblood";
  rating: number; // 1–5 (факты биографии 0–5)
  note: string;
  cost?: number;  // своя цена за уровень (для своих записей; 0 = договорная)
}

export interface VtmGearItem {
  id: string;
  name: string;
  count: string;
  note: string;
}

export interface VtmNote {
  id: string;
  title: string;
  content: string;
  date: string;
}

export interface VtmTrackers {
  humanity: number;    // 0–10
  stains: number;      // пятна Человечности
  hunger: number;      // 0–5
  healthSup: number;   // поверхностный урон (Здоровье)
  healthAgg: number;   // тяжёлый урон (Здоровье)
  wpSup: number;       // поверхностный урон (Воля)
  wpAgg: number;       // тяжёлый урон (Воля)
  xp: number;          // свободный опыт
  xpSpent: number;     // вложено всего
  huntCount: number;   // сколько «новых охот» начато (сколько ночей прожито)
  lastHunt: string;    // дата последней «новой охоты» (ru-RU)
}

export interface VtmSheetData {
  info: VtmInfo;
  attributes: VtmAttributes;
  skills: VtmSkillState[];
  disciplines: VtmDisciplineState[];
  advantages: VtmAdvantageEntry[]; // факты биографии + достоинства + недостатки
  loresheets: { sheetId: string; level: number; note: string }[]; // листоги («Истории», стр. 384+)
  diablerie: { count: number; notes: string }; // совершённые Диаблери и след в ауре
  gear: {
    haven: string;      // убежище
    resources: string;  // деньги / источники дохода
    items: VtmGearItem[];
  };
  notes: {
    draft: string;
    entries: VtmNote[];
  };
  trackers: VtmTrackers;
  rollLog: { id: string; text: string; ts: string }[];
  xpLog: { id: string; text: string; ts: string }[]; // журнал опыта (получено/потрачено)
  resonance: VtmResonance; // текущий резонанс крови (привкус эмоций; kind="" — не выбран)
  advV2?: boolean; // семантика достоинств: rating = УРОВЕНЬ (а не очки). false — лист старого образца
}

