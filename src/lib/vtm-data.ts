// ---------- Нормализация (совместимость старых листов) ----------

function clampInt(v: unknown, min: number, max: number): number {
  const n = Math.floor(Number(v));
  if (Number.isNaN(n)) return min;
  return Math.max(min, Math.min(max, n));
}

function asString(v: unknown): string {
  return typeof v === "string" ? v : "";
}

export function normalizeSheet(input: unknown): VtmSheetData {
  const base = emptySheet();
  if (!input || typeof input !== "object") return base;
  const raw = input as Record<string, any>;

  // info
  if (raw.info && typeof raw.info === "object") {
    const i = raw.info as Record<string, any>;
    Object.assign(base.info, {
      name: asString(i.name),
      concept: asString(i.concept),
      chronicle: asString(i.chronicle),
      sire: asString(i.sire),
      occupation: asString(i.occupation),
      generation: clampInt(i.generation, 0, 16),
      sect: asString(i.sect),
      clan: asString(i.clan),
      predator: asString(i.predator),
      ambition: asString(i.ambition),
      desire: asString(i.desire),
      principle1: asString(i.principle1),
      principle2: asString(i.principle2),
      principle3: asString(i.principle3),
      anchor1: asString(i.anchor1),
      anchor2: asString(i.anchor2),
      anchor3: asString(i.anchor3),
      description: asString(i.description),
      history: asString(i.history),
      portrait: asString(i.portrait),
      portraitThumb: asString(i.portraitThumb),
    });
  }

  // attributes
  if (raw.attributes && typeof raw.attributes === "object") {
    for (const key of Object.keys(base.attributes) as (keyof VtmAttributes)[]) {
      base.attributes[key] = clampInt(raw.attributes[key], 0, 5);
    }
  }

  // skills — нормализуем по библиотеке (ключ = id, имя = отображение)
  if (Array.isArray(raw.skills)) {
    base.skills = raw.skills
      .filter((s: any) => s && typeof s === "object")
      .map((s: any) => {
        const key = typeof s.key === "string" && SKILL_LIBRARY.some((d) => d.id === s.key) ? s.key : null;
        const libDef = key ? SKILL_LIBRARY.find((d) => d.id === key) : null;
        const name = libDef ? libDef.name : asString(s.name) || "Навык";
        return {
          key,
          name,
          value: clampInt(s.value, 0, 5),
          spec: asString(s.spec),
          xp: clampInt(s.xp, 0, 999),
        } as VtmSkillState;
      });
  }

  // disciplines
  if (Array.isArray(raw.disciplines)) {
    base.disciplines = raw.disciplines
      .filter((d: any) => d && typeof d === "object")
      .map((d: any) => {
        const key = typeof d.key === "string" && DISCIPLINES.some((x) => x.id === d.key) ? d.key : null;
        const libDef = key ? DISCIPLINE_BY_ID.get(key) : null;
        const name = libDef ? libDef.name : asString(d.name) || "Дисциплина";
        const powers: Record<number, string> = {};
        if (d.powers && typeof d.powers === "object") {
          for (const [lvl, name2] of Object.entries(d.powers)) {
            const n = parseInt(lvl, 10);
            if (n >= 1 && n <= 5 && typeof name2 === "string") powers[n] = name2;
          }
        }
        return {
          key,
          name,
          value: clampInt(d.value, 0, 5),
          powers,
          xp: clampInt(d.xp, 0, 999),
          // свои Дисциплины: описание и описания сил по уровням (полная кастомизация)
          description: typeof d.description === "string" ? d.description.slice(0, 600) : undefined,
          powerNotes: (() => {
            if (!d.powerNotes || typeof d.powerNotes !== "object") return undefined;
            const notes: Record<number, string> = {};
            for (const [lvl, note] of Object.entries(d.powerNotes)) {
              const n = parseInt(lvl, 10);
              if (n >= 1 && n <= 5 && typeof note === "string") notes[n] = note.slice(0, 600);
            }
            return Object.keys(notes).length ? notes : undefined;
          })(),
        } as VtmDisciplineState;
      });
  }

  // advantages
  if (Array.isArray(raw.advantages)) {
    base.advantages = raw.advantages
      .filter((a: any) => a && typeof a === "object")
      .map((a: any, idx: number) => ({
        id: asString(a.id) || vtmUid(`adv-${idx}`),
        name: asString(a.name) || "Преимущество",
        kind: (["background", "merit", "flaw", "thinblood"].includes(a.kind) ? a.kind : "merit") as VtmAdvantageEntry["kind"],
        rating: clampInt(a.rating, 0, 5),
        note: asString(a.note),
        cost: a.cost == null ? undefined : clampInt(a.cost, 0, 9), // своя цена за уровень (свои записи)
      }));
    // Одноразовая миграция старых листов: раньше rating = ОЧКИ, теперь rating = УРОВЕНЬ.
    if (raw.advV2 !== true) {
      for (const a of base.advantages) {
        if (a.kind === "background") continue;
        const def = ADVANTAGE_LIBRARY.find((d) => d.name === a.name);
        if (!def || !def.cost) continue; // свои записи — не трогаем
        if (def.max === 1) { a.rating = 1; continue; } // фиксированная сила — один уровень
        if (def.cost > 1 && a.rating % def.cost === 0 && a.rating / def.cost <= def.max) {
          a.rating = a.rating / def.cost; // старые очки делим на цену за уровень
        } else if (a.rating > def.max) {
          a.rating = def.max;
        }
      }
    }
  }
  base.advV2 = true;

  // loresheets («Истории», стр. 384+): только известные листоги, уровень 0..4
  if (Array.isArray(raw.loresheets)) {
    base.loresheets = raw.loresheets
      .filter((l: any) => l && typeof l === "object" && LORESHEET_BY_ID.has(asString(l.sheetId)))
      .map((l: any) => ({
        sheetId: asString(l.sheetId),
        level: clampInt(l.level, 0, 4),
        note: asString(l.note),
      }))
      .filter((l: { sheetId: string; level: number; note: string }) => l.sheetId !== "");
  }

  // diablerie: счётчик и след в ауре
  if (raw.diablerie && typeof raw.diablerie === "object") {
    const db = raw.diablerie as Record<string, any>;
    base.diablerie = {
      count: clampInt(db.count, 0, 99),
      notes: asString(db.notes),
    };
  }

  // gear
  if (raw.gear && typeof raw.gear === "object") {
    const g = raw.gear as Record<string, any>;
    base.gear.haven = asString(g.haven);
    base.gear.resources = asString(g.resources);
    if (Array.isArray(g.items)) {
      base.gear.items = g.items
        .filter((it: any) => it && typeof it === "object")
        .map((it: any, idx: number) => ({
          id: asString(it.id) || vtmUid(`item-${idx}`),
          name: asString(it.name),
          count: asString(it.count),
          note: asString(it.note),
        }));
    }
  }

  // notes
  if (raw.notes && typeof raw.notes === "object") {
    const n = raw.notes as Record<string, any>;
    base.notes.draft = asString(n.draft);
    if (Array.isArray(n.entries)) {
      base.notes.entries = n.entries
        .filter((e: any) => e && typeof e === "object")
        .map((e: any, idx: number) => ({
          id: asString(e.id) || vtmUid(`note-${idx}`),
          title: asString(e.title),
          content: asString(e.content),
          date: asString(e.date),
        }));
    }
  }

  // trackers
  if (raw.trackers && typeof raw.trackers === "object") {
    const t = raw.trackers as Record<string, any>;
    base.trackers = {
      humanity: clampInt(t.humanity, 0, 10),
      stains: clampInt(t.stains, 0, 10),
      hunger: clampInt(t.hunger, 0, 5),
      healthSup: clampInt(t.healthSup, 0, 20),
      healthAgg: clampInt(t.healthAgg, 0, 20),
      wpSup: clampInt(t.wpSup, 0, 20),
      wpAgg: clampInt(t.wpAgg, 0, 20),
      xp: clampInt(t.xp, 0, 9999),
      xpSpent: clampInt(t.xpSpent, 0, 9999),
      huntCount: clampInt(t.huntCount, 0, 9999),
      lastHunt: asString(t.lastHunt),
    };
  }

  // roll log
  if (Array.isArray(raw.rollLog)) {
    base.rollLog = raw.rollLog
      .filter((r: any) => r && typeof r === "object")
      .slice(0, 60)
      .map((r: any, idx: number) => ({
        id: asString(r.id) || `roll-${idx}`,
        text: asString(r.text),
        ts: asString(r.ts),
      }));
  }

  // резонанс крови (обратная совместимость: старые листы без резонанса)
  if (raw.resonance && typeof raw.resonance === "object") {
    const r = raw.resonance as Record<string, any>;
    base.resonance = {
      kind: typeof r.kind === "string" && RESONANCE_BY_ID.has(r.kind) ? r.kind : "",
      intensity: clampInt(r.intensity, 0, 5),
    };
  }

  // xp log (обратная совместимость: старые листы без журнала опыта)
  if (Array.isArray(raw.xpLog)) {
    base.xpLog = raw.xpLog
      .filter((r: any) => r && typeof r === "object")
      .slice(0, 40)
      .map((r: any, idx: number) => ({
        id: asString(r.id) || `xp-${idx}`,
        text: asString(r.text),
        ts: asString(r.ts),
      }));
  }

  // --- Кровные узы (bonds) ---
  if (Array.isArray(raw.bonds)) {
    base.bonds = raw.bonds
      .filter((b: any) => b && typeof b === "object")
      .slice(0, 30)
      .map((b: any, idx: number) => ({
        id: asString(b.id) || vtmUid(`bond-${idx}`),
        name: asString(b.name),
        kind: (["vampire", "ghoul", "mortal"].includes(b.kind) ? b.kind : "vampire") as VtmBondEntry["kind"],
        direction: (["regard", "regarded"].includes(b.direction) ? b.direction : "regard") as VtmBondEntry["direction"],
        stage: b.vinculum ? 99 : clampInt(b.stage, 0, 3),
        vinculum: b.vinculum ? clampInt(b.vinculum, 1, 10) : undefined,
        note: asString(b.note),
      }));
  }

  // --- Котерия (coterie) ---
  if (raw.coterie && typeof raw.coterie === "object") {
    const c = raw.coterie as Record<string, any>;
    base.coterie = {
      name: asString(c.name),
      type: (["", "camarilla", "anarch", "sabbat", "autarkis", "cult"].includes(c.type) ? c.type : "") as VtmCoterieData["type"],
      tieKind: (["", "sense", "influence", "sins"].includes(c.tieKind) ? c.tieKind : "") as VtmCoterieData["tieKind"],
      tieNote: asString(c.tieNote),
      clanMerit: asString(c.clanMerit),
      members: Array.isArray(c.members)
        ? c.members
            .filter((m: any) => m && typeof m === "object")
            .slice(0, 20)
            .map((m: any, idx: number) => ({
              id: asString(m.id) || vtmUid(`cot-${idx}`),
              name: asString(m.name),
              clan: asString(m.clan),
              role: asString(m.role),
              vinculum: m.vinculum == null ? undefined : clampInt(m.vinculum, 0, 10),
            }))
        : [],
    };
  }

  // --- Долги престации (boons) ---
  if (Array.isArray(raw.boons)) {
    base.boons = raw.boons
      .filter((b: any) => b && typeof b === "object")
      .slice(0, 40)
      .map((b: any, idx: number) => ({
        id: asString(b.id) || vtmUid(`boon-${idx}`),
        kind: (["trivial", "minor", "major", "life", "blood"].includes(b.kind) ? b.kind : "minor") as VtmBoonEntry["kind"],
        direction: (["owed", "owing"].includes(b.direction) ? b.direction : "owing") as VtmBoonEntry["direction"],
        party: asString(b.party),
        status: (["open", "paid", "broken"].includes(b.status) ? b.status : "open") as VtmBoonEntry["status"],
        note: asString(b.note),
        date: asString(b.date),
      }));
  }

  // --- Убеждения и Якоря (convictions) ---
  if (Array.isArray(raw.convictions)) {
    base.convictions = raw.convictions
      .filter((c: any) => c && typeof c === "object")
      .slice(0, 8)
      .map((c: any, idx: number) => ({
        id: asString(c.id) || vtmUid(`conv-${idx}`),
        conviction: asString(c.conviction),
        touchstone: asString(c.touchstone),
        broken: !!c.broken,
        note: asString(c.note),
      }));
  }

  // --- Торпор (torpor) ---
  if (raw.torpor && typeof raw.torpor === "object") {
    const tp = raw.torpor as Record<string, any>;
    base.torpor = {
      inTorpor: !!tp.inTorpor,
      since: asString(tp.since),
      humanity: clampInt(tp.humanity, 0, 10),
      note: asString(tp.note),
    };
  }

  return base;
}

