// ---------- Типы ----------

export interface VtmInfo {
  name: string;        // имя вампира
  concept: string;     // концепция (кем был / кем стал)
  chronicle: string;   // хроника
  sire: string;        // сир (создатель)
  occupation: string;  // род деятельности (смертная профессия / род занятий)
  generation: number;  // поколение 5..16 (0 = не выбрано)
  sect: string;        // id секты из SECTS
  clan: string;        // id клана из CLANS (включая caitif / thinblood)
  predator: string;    // id стиля охоты из PREDATOR_TYPES
  ambition: string;    // Цель (большая, на всю хронику)
  desire: string;      // Желание (ближняя цель, текущая арка)
  principle1: string;  // Принцип 1 («никогда…» / «всегда…»)
  principle2: string;  // Принцип 2
  principle3: string;  // Принцип 3
  anchor1: string;     // Опора 1 (кто держит Человечность)
  anchor2: string;     // Опора 2
  anchor3: string;     // Опора 3
  description: string; // внешность
  history: string;     // предыстория
  portrait: string;      // dataURL (до 480px)
  portraitThumb: string; // dataURL (96px) для карточек архива
}

export interface VtmAttributes {
  str: number; // Сила
  dex: number; // Ловкость
  sta: number; // Выносливость
  cha: number; // Обаяние
  man: number; // Манипуляция
  com: number; // Самообладание
  int: number; // Интеллект
  wit: number; // Смекалка
  res: number; // Упорство
}

export interface VtmSkillState {
  key: string | null; // id из SKILL_LIBRARY или null для кастомного
  name: string;
  value: number; // 0–5
  spec: string;  // специализация («выслеживание», «палинг…»)
  xp: number;    // вложено опыта (для истории прокачки)
}

export interface VtmDisciplineState {
  key: string | null;  // id из DISCIPLINES или null для редкой/своей
  name: string;
  value: number;       // 0–5
  powers: Record<number, string>; // уровень → выбранная сила (название)
  xp: number;
  description?: string;          // описание своей Дисциплины (полная кастомизация)
  powerNotes?: Record<number, string>; // уровень → описание своей силы
}

export interface VtmAdvantageEntry {
  id: string;
  name: string;
  kind: "background" | "merit" | "flaw" | "thinblood";
  rating: number; // 1–5 (факты биографии 0–5)
  note: string;
  cost?: number;  // своя цена за уровень (для своих записей; 0 = договорная)
}

export interface VtmGearItem {
  id: string;
  name: string;
  count: string;
  note: string;
}

export interface VtmNote {
  id: string;
  title: string;
  content: string;
  date: string;
}

export interface VtmTrackers {
  humanity: number;    // 0–10
  stains: number;      // пятна Человечности
  hunger: number;      // 0–5
  healthSup: number;   // поверхностный урон (Здоровье)
  healthAgg: number;   // тяжёлый урон (Здоровье)
  wpSup: number;       // поверхностный урон (Воля)
  wpAgg: number;       // тяжёлый урон (Воля)
  xp: number;          // свободный опыт
  xpSpent: number;     // вложено всего
  huntCount: number;   // сколько «новых охот» начато (сколько ночей прожито)
  lastHunt: string;    // дата последней «новой охоты» (ru-RU)
}

export interface VtmSheetData {
  info: VtmInfo;
  attributes: VtmAttributes;
  skills: VtmSkillState[];
  disciplines: VtmDisciplineState[];
  advantages: VtmAdvantageEntry[]; // факты биографии + достоинства + недостатки
  loresheets: { sheetId: string; level: number; note: string }[]; // листоги («Истории», стр. 384+)
  diablerie: { count: number; notes: string }; // совершённые Диаблери и след в ауре
  gear: {
    haven: string;      // убежище
    resources: string;  // деньги / источники дохода
    items: VtmGearItem[];
  };
  notes: {
    draft: string;
    entries: VtmNote[];
  };
  trackers: VtmTrackers;
  rollLog: { id: string; text: string; ts: string }[];
  xpLog: { id: string; text: string; ts: string }[]; // журнал опыта (получено/потрачено)
  resonance: VtmResonance; // текущий резонанс крови (привкус эмоций; kind="" — не выбран)
  advV2?: boolean; // семантика достоинств: rating = УРОВЕНЬ (а не очки). false — лист старого образца
  // --- Новые механики (V5 Companion + Gehenna War + In Memoriam) ---
  bonds?: VtmBondEntry[];        // Кровные узы / Винкулум
  coterie?: VtmCoterieData;      // Котерия и её общие связи
  boons?: VtmBoonEntry[];        // Долги престации
  convictions?: VtmConvictionEntry[]; // Убеждения и Якоря (структурированно)
  torpor?: VtmTorporState;       // Состояние торпора
}

// ---------- Резонанс крови ----------

export interface VtmResonance {
  kind: string;     // id из RESONANCES ("" — не выбран)
  intensity: number; // 0–5 (0 — не отслеживается)
}

// ---------- Кровные узы (Blood Bond / Vinculum) ----------
// «Схема связей»: кто кому пил кровь и на какой стадии. Направление = чью кровь
// пьёт персонаж → к кому его тянет; обратное — чью кровь пили, чтобы его привязать.
// stage: 1 — влюблённость, 2 — преданность, 3 — рабство.

export interface VtmBondEntry {
  id: string;
  name: string;          // имя связанного
  kind: "vampire" | "ghoul" | "mortal";
  direction: "regard" | "regarded"; // regard = ты пил его кровь (тянет к нему); regarded = он пил твою (ты — его регнант)
  stage: number;         // 0 — узы сняты/слабли; 1–3 — стадия; 99 — Винкулум с рейтингом (см. vinculum)
  vinculum?: number;     // для Sabbat-Винкулума: рейтинг 1–10 (тогда stage игнорируется)
  note: string;
}

// ---------- Котерия (Coterie) ----------
// Стая-связка Сородичей. Хранит имя, состав, общую «связь крови» (Blood Tie)
// и клановое достоинство котерии (если есть).

export interface VtmCoterieMember {
  id: string;
  name: string;
  clan: string;         // id клана из CLANS или свободный текст
  role: string;         // роль: Лидер, Мышь, Кулак, Кровь и т.д.
  vinculum?: number;    // Винкулум этого члена к персонажу (1–10, для Sabbat-котерий)
}

export interface VtmCoterieData {
  name: string;         // имя котерии
  type: "" | "camarilla" | "anarch" | "sabbat" | "autarkis" | "cult"; // тип/устав
  tieKind: "" | "sense" | "influence" | "sins"; // Blood Tie: Кровное чутьё/влияние/грехи
  tieNote: string;      // что связывает (общая кровь, общий враг, клятва и т.п.)
  clanMerit: string;    // id кланового достоинства котерии (cc_*) или ""
  members: VtmCoterieMember[];
}

// ---------- Долги престации (Boons / Prestation) ----------
// Журнал одолжений между Сородичами. Тип — от Тривиального до Жизни и Кровавого.

export interface VtmBoonEntry {
  id: string;
  kind: "trivial" | "minor" | "major" | "life" | "blood";
  direction: "owed" | "owing"; // owed = тебе должны; owing = ты должен
  party: string;         // имя Сородича
  status: "open" | "paid" | "broken";
  note: string;
  date: string;
}

// ---------- Убеждения и Якоря (Convictions & Touchstones) ----------
// Структурированная надстройка над принципами/якорями из info: каждое Убеждение
// связано с живым Якорем, а гибель Якоря лишает Убеждения и насылает Пятна.

export interface VtmConvictionEntry {
  id: string;
  conviction: string;   // во что верит
  touchstone: string;   // живой человек (или место) — якорь
  broken: boolean;      // Якорь утрачен (гибель/Обращение/порча)
  note: string;
}

// ---------- Торпор (Torpor) ----------
// Краткое состояние, когда вампир «мёртв для мира»: длительность зависит от Человечности.

export interface VtmTorporState {
  inTorpor: boolean;
  since: string;        // дата ухода в торпор
  humanity: number;     // Человечность на момент ухода — определяет срок
  note: string;
}

