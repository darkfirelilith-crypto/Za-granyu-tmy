/** Сила Крови по поколению при создании персонажа (стр. 151 книги правил). */
export function bloodPotencyByGeneration(generation: number): number {
  if (generation >= 14) return 0; // 14–16: слабокровные
  if (generation >= 12) return 1; // 12–13: неонаты
  if (generation >= 10) return 2; // 10–11: анциллы
  if (generation >= 8) return 3;  // 8–9: старейшины (по согласованию с рассказчиком)
  return 4; // 5–7:methuseльцы — редкость, по согласованию
}

