// ---------- Случайный выбор ----------

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

// ---------- Генерация события ночи ----------

export function generateNightEvent(): NightEvent {
  return {
    id: `night-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    dayEvent: pick(DAY_EVENTS),
    nightThreat: pick(NIGHT_THREATS),
    visitor: pick(VISITORS),
    sign: pick(SIGNS),
    rumor: pick(RUMORS),
    opportunity: pick(OPPORTUNITIES),
    complication: pick(COMPLICATIONS),
    mood: pick(MOODS),
  };
}

export function generateNightBatch(count: number): NightEvent[] {
  const events: NightEvent[] = [];
  for (let i = 0; i < count; i++) {
    events.push(generateNightEvent());
  }
  return events;
}

