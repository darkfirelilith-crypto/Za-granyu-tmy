// ---------- Генерация сцены ----------

export function generateHuntScene(): HuntScene {
  const loc = pick(HUNT_LOCATIONS);
  const victim = pick(HUNT_VICTIMS);
  const { difficulty, diceHint } = difficultyFor(victim.intensity);
  const complication = pick(HUNT_COMPLICATIONS);
  const reward = pick(HUNT_REWARDS);
  const risk = pick(HUNT_RISKS);
  const includeTwist = Math.random() < 0.3;
  const twist = includeTwist ? pick(HUNT_TWISTS) : undefined;

  return {
    id: `hunt-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    location: loc.name,
    victim: victim.name,
    victimDesc: victim.desc,
    predatorStyle: PREDATOR_NAMES[loc.style] || loc.style,
    difficulty,
    diceHint,
    resonance: RESONANCE_NAMES[victim.resonance] || victim.resonance,
    resonanceIntensity: victim.intensity,
    complication,
    reward,
    risk,
    twist,
  };
}

// ---------- Пакет сцен для Рассказчика ----------

export function generateHuntBatch(count: number): HuntScene[] {
  const scenes: HuntScene[] = [];
  for (let i = 0; i < count; i++) {
    scenes.push(generateHuntScene());
  }
  return scenes;
}

