// ---------- Случайный выбор ----------

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function difficultyFor(victimIntensity: number): { difficulty: number; diceHint: string } {
  const d = Math.min(5, Math.max(1, Math.ceil(victimIntensity / 1.2)));
  const hints = [
    "Ловкость + Скрытность (1 успех)",
    "Манипуляция + Лицедейство (2 успеха)",
    "Сила + Драка или Манипуляция + Убеждение (2 успеха)",
    "Решимость + Запугивание или Самообладание + Сокрытие (3 успеха)",
    "Кровавая магия / Забвение + социальный пул (3 успеха, риск Френзии)",
  ];
  return { difficulty: d, diceHint: hints[d - 1] };
}

