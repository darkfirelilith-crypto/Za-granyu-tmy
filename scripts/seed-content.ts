import { PrismaClient } from '@prisma/client'
const db = new PrismaClient()
async function main() {
  const items = [
    { key: 'guild_history', title: 'История Гильдии', body: 'Гильдия Авантюристов была основана спустя десять лет после Сумеречной Войны, когда стало ясно: разрозненные герои не способны противостоять новым угрозам. Шесть народов подписали Великий Устав Гильдии, даровав ей право вербовать, награждать и судить искателей приключений вне границ государств.\n\nС тех пор любой, кто желает ступить на путь авантюры, обязан получить знак Гильдии. Без него наём вне закона, а помощь в беде — лишь дело доброго сердца, а не долга.' },
    { key: 'guild_motto', title: 'Девиз Гильдии', body: '«Свет не гаснет, пока стоит хоть один»' },
    { key: 'guild_halls', title: 'Залы Гильдии', body: '• Аэтерхолд — главный зал\n• Порт-Моррай — морской зал\n• Каз-Думар — подгорный зал\n• Аэнорэль — лесной зал' },
    { key: 'hall_intro', title: 'За гранью тьмы', body: 'Перед тобой — врата в мир, что за гранью тьмы. Здесь, среди пыльных свитков и мерцающих рун, хранятся предания народов, деяния героев и тайны, что дремлют за печатью Гримуара.' },
  ]
  for (const it of items) {
    await db.siteContent.upsert({ where: { key: it.key }, update: {}, create: it })
  }
  console.log('Seeded', items.length, 'site content entries')
}
main().catch(e=>{console.error(e);process.exit(1)}).finally(()=>db.$disconnect())
